#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Релятивистский калькулятор полёта до Проксимы Центавра.

Профиль миссии: разгон -> крейсер -> торможение.
  1. Разгон с постоянным СОБСТВЕННЫМ ускорением a до крейсерской скорости v_c.
  2. Равномерный полёт (крейсер) на v_c.
  3. Симметричное торможение с тем же a до полной остановки у цели.

Учитывается полная СТО (специальная теория относительности):
считаются и время по Земле (координатное), и собственное время экипажа
(с учётом замедления времени / дилатации).

Если на половине пути крейсерская скорость недостижима (x1 > D/2),
автоматически включается режим "разгон-торможение" без крейсерской фазы
(брахистохрона) — корабль разгоняется ровно до середины, затем тормозит.

Формулы гиперболического (равноускоренного по СТО) движения:
  gamma = 1 / sqrt(1 - beta^2),  beta = v_c / c
  x1  = (c^2 / a) * (gamma - 1)            # дистанция фазы разгона
  t1  = gamma * v_c / a                    # время разгона по Земле
  tau1 = (c / a) * artanh(beta)            # собственное время разгона
Для режима без крейсера (разгон до середины пути D/2):
  gamma_mid задаётся из x1 = D/2  ->  gamma_mid = 1 + a*D/(2*c^2)
"""

import math

# --- Физические константы ---
C = 299_792_458.0           # скорость света, м/с
G = 9.80665                 # стандартное ускорение свободного падения, м/с^2
LY = 9.460_730_472_5808e15  # световой год, м
YEAR = 365.25 * 24 * 3600   # юлианский год, с

# --- Параметры миссии (значения по умолчанию) ---
DISTANCE_LY = 4.2465        # расстояние до Проксимы Центавра, св. лет
ACCEL = 1.0 * G             # ускорение по умолчанию: 1g


def fmt_time(seconds: float) -> str:
    """Человекочитаемое представление времени."""
    years = seconds / YEAR
    if years >= 1:
        return f"{years:.3f} лет"
    days = seconds / (24 * 3600)
    if days >= 1:
        return f"{days:.2f} дней"
    return f"{seconds / 3600:.2f} ч"


def compute(distance_ly: float, accel: float, cruise_beta: float) -> dict:
    """
    Расчёт миссии для заданной крейсерской скорости (в долях c).

    Возвращает словарь с ключевыми величинами.
    """
    D = distance_ly * LY
    a = accel
    beta_c = cruise_beta
    v_c = beta_c * C
    gamma_c = 1.0 / math.sqrt(1.0 - beta_c**2)

    # Дистанция фазы разгона при достижении v_c
    x1 = (C**2 / a) * (gamma_c - 1.0)

    if 2.0 * x1 <= D:
        # --- Режим с крейсерской фазой ---
        mode = "крейсер"
        t1 = gamma_c * v_c / a                       # время разгона (Земля)
        tau1 = (C / a) * math.atanh(beta_c)          # собств. время разгона
        x2 = D - 2.0 * x1                            # крейсерская дистанция
        t2 = x2 / v_c                                # время крейсера (Земля)
        tau2 = t2 / gamma_c                          # собств. время крейсера

        T = 2.0 * t1 + t2                            # полное время (Земля)
        tau = 2.0 * tau1 + tau2                      # полное собств. время
        v_max = v_c
        beta_max = beta_c
        gamma_max = gamma_c
    else:
        # --- Режим без крейсера: разгон до D/2, затем торможение ---
        mode = "без крейсера (брахистохрона)"
        # На середине пройдено D/2: gamma_mid = 1 + a*(D/2)/c^2
        gamma_mid = 1.0 + a * (D / 2.0) / C**2
        beta_mid = math.sqrt(1.0 - 1.0 / gamma_mid**2)
        v_mid = beta_mid * C
        t_half = gamma_mid * v_mid / a               # время до середины (Земля)
        tau_half = (C / a) * math.atanh(beta_mid)    # собств. время до середины

        T = 2.0 * t_half
        tau = 2.0 * tau_half
        v_max = v_mid
        beta_max = beta_mid
        gamma_max = gamma_mid

    return {
        "beta_cruise": beta_c,
        "mode": mode,
        "T_earth_s": T,
        "tau_ship_s": tau,
        "beta_max": beta_max,
        "gamma_max": gamma_max,
        "v_max_kms": v_max / 1000.0,
        "dilation": T / tau,  # во сколько раз время на Земле > времени экипажа
    }


def main():
    print("=" * 78)
    print("ПОЛЁТ ДО ПРОКСИМЫ ЦЕНТАВРА — релятивистский расчёт")
    print(f"Расстояние: {DISTANCE_LY} св. лет  |  Ускорение: {ACCEL / G:.2f}g "
          f"({ACCEL:.3f} м/с²)")
    print("Профиль: разгон → крейсер → торможение")
    print("=" * 78)

    cruise_speeds = [0.1, 0.2, 0.5, 0.8, 0.99]

    header = (f"{'v_крейс':>8} | {'режим':<26} | {'T (Земля)':>14} | "
              f"{'τ (экипаж)':>14} | {'γ_max':>7} | {'дилатация':>10}")
    print(header)
    print("-" * len(header))

    for b in cruise_speeds:
        r = compute(DISTANCE_LY, ACCEL, b)
        print(f"{r['beta_cruise']:>7.2f}c | {r['mode']:<26} | "
              f"{fmt_time(r['T_earth_s']):>14} | {fmt_time(r['tau_ship_s']):>14} | "
              f"{r['gamma_max']:>7.3f} | {r['dilation']:>9.2f}×")

    print("=" * 78)
    print("Примечания:")
    print("  T (Земля)   — время полёта по часам наблюдателя на Земле")
    print("  τ (экипаж)  — собственное время на борту (с учётом замедления)")
    print("  γ_max       — максимальный Лоренц-фактор за полёт")
    print("  дилатация   — во сколько раз земное время больше бортового")


if __name__ == "__main__":
    main()
